// Static checks of the served files: CSP-safe markup and code, the manifest and icons, the service
// worker's shell list, resolvable module imports and the vendored SDK.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, dirname, resolve, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { WEB_VERSION } from '../central_server/webapp/js/logic/homes.js';

const WEBAPP = fileURLToPath(new URL('../central_server/webapp/', import.meta.url));
const SERVED = new Set(['.html', '.js', '.mjs', '.css', '.webmanifest', '.json', '.png', '.svg', '.ico', '.txt']);

function walk(directory) {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}
const files = walk(WEBAPP).map((path) => relative(WEBAPP, path).split('\\').join('/'));
const read = (name) => readFileSync(join(WEBAPP, name), 'utf8');
const ownScripts = files.filter((name) => name.endsWith('.js') && !name.startsWith('vendor/'));

test('only servable file types (plus the vendor README) live in webapp/', () => {
  for (const name of files) assert.ok(SERVED.has(extname(name)) || name === 'vendor/README.md', name);
  assert.ok(!files.includes('config.json'), 'config.json is generated by the server, never a file');
});

test('index.html has no inline script, style or event handler and links existing files', () => {
  const html = read('index.html');
  assert.doesNotMatch(html, /<script(?![^>]*\bsrc=)[^>]*>/i, 'inline script');
  assert.doesNotMatch(html, /\son[a-z]+\s*=/i, 'inline event handler');
  assert.doesNotMatch(html, /\sstyle\s*=/i, 'style attribute');
  assert.doesNotMatch(html, /<style/i, 'style element');
  assert.match(html, /<script type="module" src="js\/app\.js"><\/script>/);
  assert.match(html, /name="viewport" content="[^"]*viewport-fit=cover/);
  assert.match(html, /name="apple-mobile-web-app-capable" content="yes"/);
  assert.match(html, /name="apple-mobile-web-app-status-bar-style" content="black-translucent"/);
  assert.match(html, /name="theme-color" content="#0F1724"/);
  assert.match(html, /rel="apple-touch-icon" href="apple-touch-icon\.png"/);
  for (const [, link] of html.matchAll(/(?:href|src)="([^"]+)"/g)) assert.ok(files.includes(link), link);
});

test('app code avoids eval, HTML strings and style attributes (CSP)', () => {
  for (const name of ownScripts.concat(['sw.js'])) {
    const code = read(name);
    assert.doesNotMatch(code, /\beval\s*\(|new Function\s*\(/, name);
    assert.doesNotMatch(code, /\.innerHTML|\.outerHTML|insertAdjacentHTML|document\.write/, name);
    assert.doesNotMatch(code, /setAttribute\(\s*['"]style['"]/, name);
    assert.doesNotMatch(code, /https?:\/\/(?!www\.w3\.org\/2000\/svg)/, name + ' must not reach other hosts');
  }
});

test('the manifest and the icons match the home-screen contract', () => {
  const manifest = JSON.parse(read('manifest.webmanifest'));
  assert.equal(manifest.name, '가족 스마트홈'); assert.equal(manifest.short_name, '스마트홈');
  assert.equal(manifest.start_url, '/app/'); assert.equal(manifest.scope, '/app/'); assert.equal(manifest.display, 'standalone');
  assert.equal(manifest.background_color, '#0F1724'); assert.equal(manifest.theme_color, '#0F1724');
  const png = (name) => {
    const data = readFileSync(join(WEBAPP, name));
    assert.equal(data.subarray(1, 4).toString(), 'PNG', name);
    const chunks = [];
    for (let offset = 8; offset < data.length;) {
      const length = data.readUInt32BE(offset), type = data.subarray(offset + 4, offset + 8).toString('latin1');
      chunks.push(type); offset += 12 + length;
    }
    for (const type of chunks) assert.ok(['IHDR', 'PLTE', 'IDAT', 'IEND', 'tRNS', 'sRGB', 'gAMA', 'pHYs'].includes(type), name + ' carries ' + type);
    return [data.readUInt32BE(16), data.readUInt32BE(20)];
  };
  for (const entry of manifest.icons) {
    const [width, height] = png(entry.src);
    assert.equal(`${width}x${height}`, entry.sizes, entry.src);
  }
  assert.ok(manifest.icons.some((entry) => entry.purpose === 'maskable'));
  assert.deepEqual(png('apple-touch-icon.png'), [180, 180]);
});

test('the service worker shell lists every served file and nothing missing', () => {
  const code = read('sw.js');
  const shell = JSON.parse('[' + /const SHELL = \[([\s\S]*?)\];/.exec(code)[1].replace(/'/g, '"').replace(/,\s*$/, '') + ']');
  for (const entry of shell) if (entry !== './') assert.ok(files.includes(entry), 'missing ' + entry);
  const expected = files.filter((name) => SERVED.has(extname(name)) && name !== 'sw.js');
  for (const name of expected) assert.ok(shell.includes(name), 'not precached: ' + name);
  assert.match(/const VERSION = '([^']+)'/.exec(code)[1], new RegExp('^' + WEB_VERSION.replace(/\./g, '\\.') + '-\\d+$'));
});

test('every relative import of the app resolves to a file', () => {
  for (const name of ownScripts) {
    const code = read(name);
    for (const [, specifier] of code.matchAll(/(?:import|export)[^'"`;]*?from\s*['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/g)) {
      if (!specifier) continue;
      assert.ok(specifier.startsWith('./') || specifier.startsWith('../'), name + ' imports ' + specifier);
      const target = resolve(dirname(join(WEBAPP, name)), specifier);
      assert.ok(existsSync(target), `${name} → ${specifier}`);
    }
    for (const [, specifier] of code.matchAll(/import\(\s*['"]([^'"]+)['"]\s*\)/g)) {
      assert.ok(existsSync(resolve(dirname(join(WEBAPP, name)), specifier)), `${name} → ${specifier}`);
    }
  }
});

test('the vendored Firebase SDK imports only its own files', () => {
  // assert.ok keeps a failure from printing the whole minified file.
  for (const name of ['firebase-app.js', 'firebase-auth.js', 'firebase-messaging.js']) {
    assert.ok(!/(?:\bfrom|\bimport)\s*\(?\s*["'`](?:https?:)?\/\//.test(read('vendor/' + name)), name + ' has a remote import');
  }
  assert.ok(read('vendor/firebase-app.js').includes('"12.19.0"'), 'firebase-app.js is the pinned release');
  assert.ok(read('vendor/firebase-auth.js').startsWith('import{') && read('vendor/firebase-auth.js').includes('from"./firebase-app.js"'));
  assert.ok(read('vendor/firebase-messaging.js').includes('from"./firebase-app.js"'));
  assert.match(read('vendor/README.md'), /\| `firebase-auth\.js` \| \d+ \| `[0-9a-f]{64}` \| `[0-9a-f]{64}` \|/);
});
